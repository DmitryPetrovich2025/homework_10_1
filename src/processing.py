from typing import List, Dict


def filter_by_state(handling_data: List[Dict], state: str = "EXECUTED") -> List:
    """Функция обработки данных с возвратом  списка по значению"""
    new_list = []
    for i in handling_data:
        if i.get("state") == state:
            new_list.append(i)
    return new_list


